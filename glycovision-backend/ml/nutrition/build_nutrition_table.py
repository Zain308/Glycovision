"""
Build services/nutrition_table.json (nutrition per 100 g for each dish the
food model knows) from published food composition tables:

  * INDB: Anuvaad Indian Nutrient Databank 2024.11 (cooked Indian recipes,
    per 100 g). Kaggle: abhinav099802/indian-nutrient-databank-indb
  * USDA FoodData Central: Survey (FNDDS) 2024-10-31 and SR Legacy 2018-04,
    https://fdc.nal.usda.gov/download-datasets (public domain)

Which entry each dish uses is in nutrition_sources.json. A dish can mix
several entries by weight (e.g. daal chawal = rice + dal).

Usage (from glycovision-backend):
    .\\venv\\Scripts\\python.exe ml\\nutrition\\build_nutrition_table.py <indb.csv> <usda-folder>
<usda-folder> holds fndds/ and srlegacy/, each with food.csv and food_nutrient.csv.
"""

import json
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "services" / "nutrition_table.json"
FIELDS = ("calories", "carbs", "protein", "fat", "fiber")
# FoodData Central nutrient ids; FNDDS files use the older nutrient numbers
# (208 energy, 205 carbohydrate, 203 protein, 204 fat, 291 fibre).
USDA_IDS = {1008: "calories", 1005: "carbs", 1003: "protein", 1004: "fat", 1079: "fiber",
            208: "calories", 205: "carbs", 203: "protein", 204: "fat", 291: "fiber"}
INDB_COLS = {"energy_kcal": "calories", "carb_g": "carbs", "protein_g": "protein", "fat_g": "fat", "fibre_g": "fiber"}
SOURCE_NAMES = {
    "INDB": "Indian Nutrient Databank (Anuvaad INDB 2024.11)",
    "FNDDS": "USDA FoodData Central, FNDDS 2024-10-31",
    "SR": "USDA FoodData Central, SR Legacy 2018-04",
}


def load_usda(folder: Path, ids: set[int]) -> tuple[dict, dict]:
    foods = pd.read_csv(folder / "food.csv", usecols=["fdc_id", "description"])
    names = dict(zip(foods.fdc_id, foods.description))
    values: dict[int, dict] = {}
    for chunk in pd.read_csv(folder / "food_nutrient.csv", usecols=["fdc_id", "nutrient_id", "amount"], chunksize=500_000):
        chunk = chunk[chunk.fdc_id.isin(ids) & chunk.nutrient_id.isin(USDA_IDS)]
        for row in chunk.itertuples():
            values.setdefault(row.fdc_id, {})[USDA_IDS[row.nutrient_id]] = float(row.amount)
    return names, values


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("Usage: python ml/nutrition/build_nutrition_table.py <indb.csv> <usda-folder>")
    indb = pd.read_csv(sys.argv[1]).set_index("food_code")
    usda_dir = Path(sys.argv[2])
    spec = json.loads((HERE / "nutrition_sources.json").read_text(encoding="utf-8"))["dishes"]

    wanted = {src: {int(code) for d in spec.values() for s, code, _ in d["parts"] if s == src} for src in ("FNDDS", "SR")}
    usda = {src: load_usda(usda_dir / folder, wanted[src]) for src, folder in (("FNDDS", "fndds"), ("SR", "srlegacy"))}

    table = {}
    for dish, entry in spec.items():
        total = {f: 0.0 for f in FIELDS}
        parts = []
        weight_sum = sum(w for _, _, w in entry["parts"])
        for src, code, weight in entry["parts"]:
            if src == "INDB":
                row = indb.loc[code]
                name = row["food_name"]
                values = {INDB_COLS[c]: float(row[c]) if pd.notna(row[c]) else 0.0 for c in INDB_COLS}
            else:
                names, all_values = usda[src]
                name = names[int(code)]
                values = all_values[int(code)]
            missing = [f for f in ("calories", "carbs", "protein", "fat") if f not in values]
            if missing:
                sys.exit(f"{dish}: {src} {code} has no {missing}")
            for f in FIELDS:
                total[f] += values.get(f, 0.0) * weight / weight_sum
            parts.append({"source": SOURCE_NAMES[src], "code": str(code), "name": name, "share": round(weight / weight_sum, 2)})
        table[dish] = {
            "per_100g": {f: round(v, 1) for f, v in total.items()},
            "match": entry["match"],
            "note": entry.get("note", ""),
            "parts": parts,
        }

    OUT.write_text(json.dumps({
        "_comment": "Generated by ml/nutrition/build_nutrition_table.py from nutrition_sources.json. Values per 100 g.",
        "dishes": table,
    }, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(table)} dishes to {OUT}")
    for dish, e in table.items():
        v = e["per_100g"]
        print(f"  {dish:15} {e['match']:9} carbs {v['carbs']:5.1f}  kcal {v['calories']:5.0f}  ({e['parts'][0]['name'][:40]})")


if __name__ == "__main__":
    main()
